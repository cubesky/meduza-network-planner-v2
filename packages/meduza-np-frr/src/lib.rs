    fn networks_missing_from_the_routing_table_are_reported() {
        let r = req(base());
        let cfg = load(&r).unwrap();
        let nets = announced_networks(&cfg, &r);
        let names: Vec<String> = nets.iter().map(ToString::to_string).collect();
        assert_eq!(names, ["10.42.10.0/24", "10.100.1.0/24", "10.99.10.0/24"]);
        // the LAN is originated; the mapping only arrived from a peer; the private LAN is not in the table at all
        let table = json!({"routes": {
            "10.42.10.0/24": [{"valid": true, "peerId": "(unspec)", "weight": 32768}],
            "10.100.1.0/24": [{"valid": true, "peerId": "10.42.1.2"}],
            "10.70.0.0/24": [{"valid": true, "peerId": "203.0.113.1"}]
        }});
        let local = local_routes(&table);
        assert_eq!(local.iter().collect::<Vec<_>>(), ["10.42.10.0/24"]);
        let st = origination_status(&nets, &local, "t").unwrap();
        assert_eq!(st.id, "frr/main/origination");
        assert_eq!(st.state, ServiceState::Degraded);
        assert_eq!(st.detail["notOriginated"], json!(["10.100.1.0/24", "10.99.10.0/24"]));
        assert_eq!(st.detail["originated"], json!(["10.42.10.0/24"]));
        assert!(st.reason.unwrap().contains("10.99.10.0/24"));
        let all = local_routes(&json!({"routes": {
            "10.42.10.0/24": [{"valid": true, "peerId": "(unspec)"}],
            "10.100.1.0/24": [{"valid": true, "peerId": "(unspec)"}],
            "10.99.10.0/24": [{"valid": false, "peerId": "10.42.1.2"}, {"valid": true, "peerId": "(unspec)"}]
        }}));
        let st = origination_status(&nets, &all, "t").unwrap();
        assert_eq!(st.state, ServiceState::Up);
        assert!(st.reason.is_none());
        assert!(origination_status(&[], &all, "t").is_none());
    }
