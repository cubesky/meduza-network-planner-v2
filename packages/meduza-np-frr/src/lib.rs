//! FRR plugin (AGENT.md §9.5, §10.4).
//!
//! Own FRR instance in the `meduza` pathspace (`-N meduza`), so it never touches a system FRR's sockets or
//! configuration; a running system FRR is reported as a conflict instead of being overridden. Daemons are
//! enabled on demand: zebra + bgpd always, bfdd only with BFD, ospfd only with Anycast.
//!
//! Roles (D17/D18): iBGP (+BFD) over the Tinc mesh carries the internal routes; eBGP over WireGuard/OpenVPN carries
//! the external ones; OSPF exists only for Anycast — every mesh member runs it over its Tinc device, and the
//! services' /30s from the manager's pool are its only routes (it runs on nothing but the carriers and VIP stubs).
//!
//! Routing policy uses large communities to mark origin and is deny-by-default:
//! - `ASN:1:1` locally originated public prefixes, `ASN:1:2` private LAN (internal only),
//! - `ASN:2:<n>` routes learned from external neighbor n.
//!
//! External export denies private first, then permits only the neighbor's explicit export set, the internal AS's
//! public routes (`exportPolicy.internal`) and — unless `noForward` — routes learned from other external peers.
//! Import accepts only routes the peer originated unless `noTransit` is off. Every route-map ends with an explicit
//! deny — no trailing permit can bypass the filters. Roaming peers (mobile, metered) never get BFD, and routes they
//! only transit are de-preferred so traffic crosses them only when no other path exists.

