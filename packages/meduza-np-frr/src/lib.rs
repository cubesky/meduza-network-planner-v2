pub fn validate(cfg: &FrrConfig, req: &PluginRequest) -> Vec<ValidationError> {
    let mut errors = validate_config(cfg, req);
    if cfg.enabled {
        errors.extend(validate_environment(cfg, req));
    }
    errors
}

// Keep configuration validation independent of the host's installed daemons and privileges.
fn validate_config(cfg: &FrrConfig, req: &PluginRequest) -> Vec<ValidationError> {
    let mut v = Validator::new();
    if !cfg.enabled {
        return Vec::new();
    }
    let asn = cfg.local_asn.or(req.config.routing.as_ref().and_then(|r| r.internal_asn));
    v.check(asn.is_some(), "/localAsn", "localAsn (or routing.internalAsn) is required");
    if let (Some(local), Some(internal)) = (cfg.local_asn, req.config.routing.as_ref().and_then(|r| r.internal_asn)) {
        if !cfg.internal_neighbors.is_empty() {
            v.check(local == internal, "/localAsn", format!("iBGP requires localAsn {local} to equal the internal ASN {internal}"));
        }
    }
    v.check(cfg.router_id.or(req.config.node.router_id).is_some(), "/routerId", "routerId required (frr.routerId or node.routerId)");
    v.check((1..=64).contains(&cfg.maximum_paths), "/maximumPaths", "1-64");
    let profiles: BTreeSet<&str> = cfg.bfd.profiles.iter().map(|p| p.id.as_str()).collect();
    let mut addrs = BTreeSet::new();
    let mut ids = BTreeSet::new();
    for (i, n) in cfg.internal_neighbors.iter().enumerate() {
        if n.roaming || roaming_node_internal(req) {
            v.check(
                n.bfd_profile.is_none(),
                format!("/internalNeighbors/{i}/bfdProfile"),
                "BFD is not used on sessions with a roaming node (it costs bandwidth); remove bfdProfile",
            );
        }
        if let Some(t) = n.timers {
            v.check(
                t.keepalive >= 1 && t.hold >= 3 && u32::from(t.keepalive) * 3 <= u32::from(t.hold),
                format!("/internalNeighbors/{i}/timers"),
                "keepalive >= 1 s and hold >= 3 x keepalive",
            );
        }
        let b = format!("/internalNeighbors/{i}");
        v.check(ids.insert(n.id.clone()), format!("{b}/id"), "duplicate neighbor id");
        v.check(addrs.insert(n.address), format!("{b}/address"), "duplicate neighbor address");
        v.check(!n.update_source.is_empty(), format!("{b}/updateSource"), "update-source must name a local address or interface");
        if n.update_source.parse::<IpAddr>().is_err() {
            v.check(validate_ifname(&n.update_source).is_ok(), format!("{b}/updateSource"), "not an address or interface name");
        }
        if let Some(p) = &n.bfd_profile {
            v.check(profiles.contains(p.as_str()), format!("{b}/bfdProfile"), format!("unknown BFD profile {p}"));
        }
    }
    if let Some(p) = &cfg.mesh_defaults.bfd_profile {
        v.check(profiles.contains(p.as_str()), "/meshDefaults/bfdProfile", format!("unknown BFD profile {p}"));
    }
    // Roaming nodes (mobile, metered) save the bandwidth BFD would cost on every session they take part in.
    let roaming_node = req.config.node.behavior == meduza_np_protocol::config::NodeBehavior::Roaming;
    if roaming_node {
        v.check(cfg.bfd.peers.is_empty(), "/bfd/peers", "BFD is not used on a roaming node (it costs bandwidth)");
        v.check(
            cfg.mesh_defaults.bfd_profile.is_none() && cfg.internal_neighbors.iter().all(|n| n.bfd_profile.is_none()),
            "/internalNeighbors",
            "BFD is not used on a roaming node (it costs bandwidth)",
        );
    }
    for (i, n) in cfg.external_neighbors.iter().enumerate() {
        let b = format!("/externalNeighbors/{i}");
        v.check(ids.insert(n.id.clone()), format!("{b}/id"), "duplicate neighbor id");
        v.check(addrs.insert(n.address), format!("{b}/address"), "duplicate neighbor address");
        v.check(
            Some(n.remote_asn) != asn,
            format!("{b}/remoteAsn"),
            "external neighbors need a different ASN (use internalNeighbors for iBGP)",
        );
        v.check(n.address.is_ipv4(), format!("{b}/address"), "only IPv4 sessions are supported by this version (§9.5)");
        if let Some(p) = &n.bfd_profile {
            v.check(profiles.contains(p.as_str()), format!("{b}/bfdProfile"), format!("unknown BFD profile {p}"));
            v.check(
                !roaming_node && !n.roaming,
                format!("{b}/bfdProfile"),
                "BFD is not used on sessions with a roaming node (it costs bandwidth); remove bfdProfile",
            );
        }
        if let Some(t) = n.timers {
            v.check(
                t.keepalive >= 1 && t.hold >= 3 && u32::from(t.keepalive) * 3 <= u32::from(t.hold),
                format!("{b}/timers"),
                "keepalive >= 1 s and hold >= 3 x keepalive",
            );
        }
        if let Some(r) = &n.password_ref {
            v.check(req.config.secrets.contains_key(r), format!("{b}/passwordRef"), format!("secret {r} was not delivered to this node"));
        }
        for (field, rules) in [("filterIn", &n.filter_in), ("filterOut", &n.filter_out)] {
            for (j, r) in rules.iter().enumerate() {
                v.check(parse_filter_rule(r).is_some(), format!("{b}/{field}/{j}"), "expected `permit|deny <IPv4 network> [ge N] [le N]`");
            }
        }
        // eBGP runs over an external connection (D17): a WireGuard or OpenVPN instance of this node.
        match &n.transport {
            Some(t) => {
                v.check(
                    meduza_np_protocol::plan::valid_instance_ref(t),
                    format!("{b}/transport"),
                    "transport must be <package>/<instance>",
                );
                v.check(
                    t.starts_with("wireguard/") || t.starts_with("openvpn/"),
                    format!("{b}/transport"),
                    "external (eBGP) sessions run over a WireGuard or OpenVPN transport; the Tinc mesh carries iBGP only",
                );
            }
            None => v.error(format!("{b}/transport"), "name the WireGuard/OpenVPN instance this eBGP session runs over"),
        }
    }
    for (i, p) in cfg.bfd.profiles.iter().enumerate() {
        // Aggressive timers on all nodes are a common outage cause on small CPUs (§9.5).
        v.check(
            p.transmit_interval >= 100 && p.receive_interval >= 100,
            format!("/bfd/profiles/{i}"),
            "intervals below 100 ms are not allowed",
        );
    }
    for (i, p) in cfg.bfd.peers.iter().enumerate() {
        v.check(profiles.contains(p.profile.as_str()), format!("/bfd/peers/{i}/profile"), format!("unknown BFD profile {}", p.profile));
    }
    if cfg.anycast.enabled {
        let any = &cfg.anycast;
        v.check(any.pool.is_some(), "/anycast/pool", "the Anycast pool (the cluster's Anycast range) is required");
        v.check(valid_area(&any.area), "/anycast/area", "area is a dotted quad or integer");
        v.check(!any.interfaces.is_empty(), "/anycast/interfaces", "at least one carrier interface (the Tinc mesh device)");
        let mut devs = BTreeSet::new();
        let mut seen: Vec<Ipv4Net> = Vec::new();
        for (i, a) in any.instances.iter().enumerate() {
            let b = format!("/anycast/instances/{i}");
            v.check(!a.prefixes.is_empty(), format!("{b}/prefixes"), "at least one VIP prefix");
            for (j, p) in a.prefixes.iter().enumerate() {
                let path = format!("{b}/prefixes/{j}");
                v.check(p.trunc() == *p, &path, format!("{p} is not a network address (use {})", p.trunc()));
                if let Some(pool) = any.pool {
                    v.check(pool.contains(p), &path, format!("{p} is outside the Anycast pool {pool}"));
                }
                v.check(!seen.iter().any(|q| q.contains(p) || p.contains(q)), &path, format!("{p} overlaps another service"));
                seen.push(*p);
            }
            let dev = a.vip_device();
            v.check(validate_ifname(&dev).is_ok(), format!("{b}/vipDevice"), "invalid interface name");
            v.check(devs.insert(dev.clone()), format!("{b}/vipDevice"), "VIP device used twice");
            v.check(!any.interfaces.iter().any(|c| c.name == dev), format!("{b}/vipDevice"), "a VIP device is not an adjacency interface");
        }
        for (j, c) in any.interfaces.iter().enumerate() {
            v.check(validate_ifname(&c.name).is_ok(), format!("/anycast/interfaces/{j}/name"), "invalid interface name");
            if let Some(p) = &c.bfd_profile {
                v.check(profiles.contains(p.as_str()), format!("/anycast/interfaces/{j}/bfdProfile"), format!("unknown BFD profile {p}"));
                v.check(!roaming_node, format!("/anycast/interfaces/{j}/bfdProfile"), "BFD is not used on a roaming node");
            }
        }
    }
    v.finish().err().unwrap_or_default()
}

fn validate_environment(cfg: &FrrConfig, req: &PluginRequest) -> Vec<ValidationError> {
    let mut v = Validator::new();
    // Optional daemons are only required when their feature is configured (§9.5 "按配置按需启用").
    if let Some(p) = req.providers.get(SLOT) {
        let dir = std::path::Path::new(&p.path).parent().map(|d| d.to_path_buf()).unwrap_or_default();
        let need = [("bfdd", !cfg.bfd.profiles.is_empty() || !cfg.bfd.peers.is_empty()), ("ospfd", cfg.anycast.enabled)];
        for (daemon, needed) in need {
            if needed && !dir.join(daemon).exists() {
                v.error("", format!("{daemon} is not installed next to {} (install the FRR {daemon} package)", p.path));
            }
        }
    }
    // FRR daemons keep CAP_SYS_ADMIN (netns/VRF support) when dropping privileges and abort without it; containers
    // do not get it by default. Refuse the configuration instead of crash-looping the daemons.
    if let Some(false) = meduza_np_plugin_sdk::has_effective_capability(meduza_np_plugin_sdk::CAP_SYS_ADMIN) {
        v.error(
            "",
            "FRR daemons need CAP_SYS_ADMIN: add it to the planner container (Podman --cap-add SYS_ADMIN, Quadlet AddCapability=SYS_ADMIN)",
        );
    }
    if let Some(path) = system_frr_running() {
        v.error(
            "",
            format!(
                "a system FRR instance is running ({path}); disable it or remove it before enabling meduza-np-frr — it is never overridden"
            ),
        );
    }
    v.finish().err().unwrap_or_default()
}

struct Sets {
    public: Vec<IpNet>,
    private: Vec<IpNet>,
    access_pools: Vec<IpNet>,
    mappings: Vec<IpNet>,
    anycast: Vec<IpNet>,
}

fn origin_sets(cfg: &FrrConfig, req: &PluginRequest) -> Sets {
    let nets = &req.config.networks;
    let originate = req.config.routing.as_ref().map(|r| r.originate.clone()).unwrap_or_default();
    let mut public = Vec::new();
    let mut mappings = Vec::new();
    if originate.lan {
        public.extend(nets.lan.iter().copied());
    }
    if originate.mappings {
        mappings.extend(nets.mappings.iter().filter(|m| m.enabled).map(|m| m.advertised));
    }
    public.extend(originate.extra.iter().copied());
    let private = if originate.private_lan { nets.private_lan.clone() } else { Vec::new() };
    // Access pools by instance id, looked up in the OpenVPN service (only those explicitly listed).
    let mut access_pools = Vec::new();
    if let Some(ovpn) = req.config.services.get("openvpn").and_then(|o| o.get("instances")).and_then(Value::as_array) {
        for id in &originate.access_pools {
            if let Some(pool) = ovpn
                .iter()
                .find(|i| i.get("id").and_then(Value::as_str) == Some(id.as_str()))
                .and_then(|i| i.pointer("/access/pool"))
                .and_then(Value::as_str)
            {
                if let Ok(n) = pool.parse() {
                    access_pools.push(n);
                }
            }
        }
    }
    let anycast = if cfg.anycast.enabled {
        cfg.anycast
            .instances
            .iter()
            .filter(|a| a.enabled && a.export_to_bgp)
            .flat_map(|a| a.prefixes.iter().map(|p| IpNet::V4(*p)))
            .collect()
    } else {
        Vec::new()
    };
    Sets { public, private, access_pools, mappings, anycast }
}

fn prefix_list(name: &str, nets: &[IpNet], out: &mut String) {
    if nets.is_empty() {
        // An empty prefix-list matches nothing only if it exists; define an explicit deny-all.
        out.push_str(&format!("ip prefix-list {name} seq 5 deny any\n"));
        return;
    }
    for (i, n) in nets.iter().enumerate() {
        out.push_str(&format!("ip prefix-list {name} seq {} permit {n}\n", (i + 1) * 5));
    }
}

fn rm(name: &str) -> String {
    name.to_ascii_uppercase().replace('-', "_")
}

/// Renders the three to four daemon configurations. Deterministic for identical input.
pub fn render(cfg: &FrrConfig, req: &PluginRequest) -> Result<BTreeMap<&'static str, String>, PluginError> {
    let asn = cfg
        .local_asn
        .or(req.config.routing.as_ref().and_then(|r| r.internal_asn))
        .ok_or_else(|| PluginError::new("invalid-config", "no ASN"))?;
    let rid = cfg.router_id.or(req.config.node.router_id).ok_or_else(|| PluginError::new("invalid-config", "no router id"))?;
    let host = req.config.node.id.as_str();
    let sets = origin_sets(cfg, req);
    let roaming = req.config.node.behavior == meduza_np_protocol::config::NodeBehavior::Roaming;
    let header = |daemon: &str| {
        format!("frr defaults traditional\nhostname {host}-{daemon}\nlog stdout informational\nservice integrated-vtysh-config\n!\n")
    };
    let mut files = BTreeMap::new();

    // No `ip protocol ospf route-map` filter: FRR 10 routes zebra's route-map commands through mgmtd, which this
    // instance does not run (found in the lab). OSPF stays Anycast-only by construction instead — see ospfd below.
    files.insert("zebra", format!("{}! zebra: routes come from bgpd/ospfd only; interfaces are managed elsewhere\n", header("zebra")));

    let mut b = header("bgpd");
    // Prefix sets and communities.
    b.push_str(&format!("bgp large-community-list standard MNP_LOCAL_PUBLIC permit {asn}:1:1\n"));
    b.push_str(&format!("bgp large-community-list standard MNP_LOCAL_PRIVATE permit {asn}:1:2\n"));
    b.push_str(&format!("bgp large-community-list standard MNP_LOCAL_ANY permit {asn}:1:1\n"));
    b.push_str(&format!("bgp large-community-list standard MNP_LOCAL_ANY permit {asn}:1:2\n"));
    b.push_str(&format!("bgp large-community-list expanded MNP_EXTERNAL permit ^{asn}:2:\n"));
    b.push_str("ip prefix-list MNP_DEFAULT seq 5 permit 0.0.0.0/0\n");
    let mut all_local: Vec<IpNet> = Vec::new();
    all_local.extend(&sets.public);
    all_local.extend(&sets.private);
    all_local.extend(&sets.access_pools);
    all_local.extend(&sets.mappings);
    all_local.extend(&sets.anycast);
    prefix_list("MNP_LOCAL_ALL", &all_local, &mut b);
    b.push_str("!\n");

    // Origination route-maps tag prefixes by class.
    b.push_str(&format!("route-map MNP_ORIG_PUBLIC permit 10\n set large-community {asn}:1:1 additive\nexit\n!\n"));
    b.push_str(&format!("route-map MNP_ORIG_PRIVATE permit 10\n set large-community {asn}:1:2 additive\nexit\n!\n"));

    for n in cfg.internal_neighbors.iter().filter(|n| n.enabled) {
        let name = rm(n.id.as_str());
        let mut seq = 5;
        let mut step = || {
            seq += 5;
            seq
        };
        if !n.allow_default {
            b.push_str(&format!("route-map MNP_INT_{name}_IN deny {}\n match ip address prefix-list MNP_DEFAULT\nexit\n", step()));
        }
        if !n.accept_transit {
            b.push_str(&format!("route-map MNP_INT_{name}_IN deny {}\n match large-community MNP_EXTERNAL\nexit\n", step()));
        } else if n.roaming {
            // What a roaming member learned outside is the last resort: any other path wins.
            b.push_str(&format!(
                "route-map MNP_INT_{name}_IN permit {}\n match large-community MNP_EXTERNAL\n set local-preference {ROAMING_TRANSIT_PREFERENCE}\n",
                step()
            ));
            if let Some(w) = n.weight {
                b.push_str(&format!(" set weight {w}\n"));
            }
            b.push_str("exit\n");
        }
        b.push_str(&format!("route-map MNP_INT_{name}_IN permit {}\n", step()));
        if let Some(lp) = n.local_preference {
            b.push_str(&format!(" set local-preference {lp}\n"));
        }
        if let Some(w) = n.weight {
            b.push_str(&format!(" set weight {w}\n"));
        }
        b.push_str("exit\n");
        b.push_str(&format!("route-map MNP_INT_{name}_IN deny 1000\nexit\n!\n"));
        let mut seq = 5;
        let mut step = || {
            seq += 5;
            seq
        };
        if !n.allow_default {
            b.push_str(&format!("route-map MNP_INT_{name}_OUT deny {}\n match ip address prefix-list MNP_DEFAULT\nexit\n", step()));
        }
        b.push_str(&format!("route-map MNP_INT_{name}_OUT permit {}\n match large-community MNP_LOCAL_ANY\nexit\n", step()));
        if n.export_external {
            b.push_str(&format!("route-map MNP_INT_{name}_OUT permit {}\n match large-community MNP_EXTERNAL\n", step()));
            if roaming {
                // A roaming member is the last resort as transit, also for members that do not know it roams.
                b.push_str(&format!(" set local-preference {ROAMING_TRANSIT_PREFERENCE}\n"));
            }
            b.push_str("exit\n");
        }
        b.push_str(&format!("route-map MNP_INT_{name}_OUT deny 1000\nexit\n!\n"));
    }

    for (idx, n) in cfg.external_neighbors.iter().filter(|n| n.enabled).enumerate() {
        let name = rm(n.id.as_str());
        let tag = idx + 1;
        // Import filters.
        if !n.import_policy.prefixes.is_empty() {
            for (i, p) in n.import_policy.prefixes.iter().enumerate() {
                let le = p.le.map(|l| format!(" le {l}")).unwrap_or_default();
                b.push_str(&format!("ip prefix-list MNP_EXT_{name}_IMPORT seq {} permit {}{le}\n", (i + 1) * 5, p.prefix));
            }
        }
        // Routes the peer originated: its AS alone, prepends allowed.
        let split_transit = n.roaming && !n.no_transit;
        if n.no_transit || split_transit {
            b.push_str(&format!("bgp as-path access-list MNP_EXT_{name}_ORIGIN seq 5 permit ^{0}(_{0})*$\n", n.remote_asn));
        }
        if !n.filter_in.is_empty() {
            rejected_prefix_list(&format!("MNP_EXT_{name}_FIN"), &n.filter_in, &mut b);
            b.push_str(&format!("route-map MNP_EXT_{name}_IN deny 2\n match ip address prefix-list MNP_EXT_{name}_FIN\nexit\n"));
        }
        let mut seq = 5;
        let mut step = || {
            seq += 5;
            seq
        };
        if !n.import_policy.allow_default {
            b.push_str(&format!("route-map MNP_EXT_{name}_IN deny {}\n match ip address prefix-list MNP_DEFAULT\nexit\n", step()));
        }
        // Never accept our own prefixes back from outside (anti-spoofing).
        b.push_str(&format!("route-map MNP_EXT_{name}_IN deny {}\n match ip address prefix-list MNP_LOCAL_ALL\nexit\n", step()));
        // noTransit: only the peer's own routes. A roaming peer's transit routes (noTransit off) are accepted with a
        // low preference after its own, so traffic crosses it only when no other path exists.
        let clauses: Vec<(bool, Option<u32>)> = if split_transit {
            vec![(true, n.local_preference), (false, Some(ROAMING_TRANSIT_PREFERENCE))]
        } else {
            vec![(n.no_transit, n.local_preference)]
        };
        for (origin_only, lp) in clauses {
            b.push_str(&format!("route-map MNP_EXT_{name}_IN permit {}\n", step()));
            if !n.import_policy.prefixes.is_empty() {
                b.push_str(&format!(" match ip address prefix-list MNP_EXT_{name}_IMPORT\n"));
            }
            if origin_only {
                b.push_str(&format!(" match as-path MNP_EXT_{name}_ORIGIN\n"));
            }
            b.push_str(&format!(" set large-community {asn}:2:{tag} additive\n"));
            // Outsiders cannot inject our origin markers.
            b.push_str(" set large-comm-list MNP_LOCAL_ANY delete\n");
            if let Some(lp) = lp {
                b.push_str(&format!(" set local-preference {lp}\n"));
            }
            if let Some(w) = n.weight {
                b.push_str(&format!(" set weight {w}\n"));
            }
            b.push_str("exit\n");
        }
        b.push_str(&format!("route-map MNP_EXT_{name}_IN deny 1000\nexit\n!\n"));

        // Export: explicit set for this neighbor.
        let mut export: Vec<IpNet> = Vec::new();
        if n.export_policy.lan {
            export.extend(&sets.public);
        }
        if n.export_policy.mappings {
            export.extend(&sets.mappings);
        }
        if n.export_policy.access_pools {
            export.extend(&sets.access_pools);
        }
        export.extend(n.export_policy.extra.iter().map(|p| IpNet::V4(*p)));
        export.retain(|p| !sets.private.contains(p));
        prefix_list(&format!("MNP_EXT_{name}_EXPORT"), &export, &mut b);
        if !n.filter_out.is_empty() {
            rejected_prefix_list(&format!("MNP_EXT_{name}_FOUT"), &n.filter_out, &mut b);
            b.push_str(&format!("route-map MNP_EXT_{name}_OUT deny 2\n match ip address prefix-list MNP_EXT_{name}_FOUT\nexit\n"));
        }
        let mut seq = 0;
        let mut step = || {
            seq += 5;
            seq
        };
        // Private first: no later permit can override it (§9.5).
        b.push_str(&format!("route-map MNP_EXT_{name}_OUT deny {}\n match large-community MNP_LOCAL_PRIVATE\nexit\n", step()));
        if !n.export_policy.default_route {
            b.push_str(&format!("route-map MNP_EXT_{name}_OUT deny {}\n match ip address prefix-list MNP_DEFAULT\nexit\n", step()));
        }
        b.push_str(&format!("route-map MNP_EXT_{name}_OUT permit {}\n match ip address prefix-list MNP_EXT_{name}_EXPORT\n match large-community MNP_LOCAL_PUBLIC\nexit\n", step()));
        if n.export_policy.internal {
            // Public routes of the whole internal AS: tagged ASN:1:1 by their originating member (external routes
            // have that marker stripped on import, so nothing learned outside can match).
            b.push_str(&format!("route-map MNP_EXT_{name}_OUT permit {}\n match large-community MNP_LOCAL_PUBLIC\nexit\n", step()));
        }
        if !n.no_forward {
            b.push_str(&format!("route-map MNP_EXT_{name}_OUT permit {}\n match large-community MNP_EXTERNAL\n", step()));
            if roaming {
                // A roaming node is the last resort as transit, also for peers that do not know it roams.
                b.push_str(&format!(" set as-path prepend {asn} {asn} {asn}\n"));
            }
            b.push_str("exit\n");
        }
        b.push_str(&format!("route-map MNP_EXT_{name}_OUT deny 1000\nexit\n!\n"));
    }

    b.push_str(&format!("router bgp {asn}\n bgp router-id {rid}\n no bgp default ipv4-unicast\n bgp network import-check\n"));
    if cfg.maximum_paths > 1 {
        b.push_str(" bgp bestpath as-path multipath-relax\n");
    }
    for n in cfg.internal_neighbors.iter().filter(|n| n.enabled) {
        b.push_str(&format!(
            " neighbor {} remote-as internal\n neighbor {} description {}\n neighbor {} update-source {}\n",
            n.address, n.address, n.id, n.address, n.update_source
        ));
        if let Some(t) = n.timers {
            b.push_str(&format!(" neighbor {} timers {} {}\n", n.address, t.keepalive, t.hold));
        }
        if let Some(p) = &n.bfd_profile {
            b.push_str(&format!(" neighbor {} bfd profile {p}\n", n.address));
        }
    }
    for n in cfg.external_neighbors.iter().filter(|n| n.enabled) {
        b.push_str(&format!(" neighbor {} remote-as {}\n neighbor {} description {}\n", n.address, n.remote_asn, n.address, n.id));
        if let Some(s) = &n.update_source {
            b.push_str(&format!(" neighbor {} update-source {s}\n", n.address));
        }
        if let Some(h) = n.ebgp_multihop {
            b.push_str(&format!(" neighbor {} ebgp-multihop {h}\n", n.address));
        }
        if let Some(t) = n.timers {
            b.push_str(&format!(" neighbor {} timers {} {}\n", n.address, t.keepalive, t.hold));
        }
        if let Some(r) = &n.password_ref {
            let pw = &req.secret(r)?.value;
            if pw.contains(['\n', '\r', ' ']) {
                return Err(PluginError::new("invalid-config", "BGP passwords must not contain whitespace"));
            }
            b.push_str(&format!(" neighbor {} password {}\n", n.address, pw.trim()));
        }
        if let Some(p) = &n.bfd_profile {
            b.push_str(&format!(" neighbor {} bfd profile {p}\n", n.address));
        }
    }
    b.push_str(" !\n address-family ipv4 unicast\n");
    let mut originated = BTreeSet::new();
    for p in sets.public.iter().chain(&sets.mappings).chain(&sets.access_pools).chain(&sets.anycast) {
        if originated.insert(*p) {
            b.push_str(&format!("  network {p} route-map MNP_ORIG_PUBLIC\n"));
        }
    }
    for p in &sets.private {
        if originated.insert(*p) {
            b.push_str(&format!("  network {p} route-map MNP_ORIG_PRIVATE\n"));
        }
    }
    for n in cfg.internal_neighbors.iter().filter(|n| n.enabled) {
        let name = rm(n.id.as_str());
        b.push_str(&format!(
            "  neighbor {} activate\n  neighbor {} route-map MNP_INT_{name}_IN in\n  neighbor {} route-map MNP_INT_{name}_OUT out\n",
            n.address, n.address, n.address
        ));
        if n.next_hop_self {
            b.push_str(&format!("  neighbor {} next-hop-self\n", n.address));
        }
    }
    for n in cfg.external_neighbors.iter().filter(|n| n.enabled) {
        let name = rm(n.id.as_str());
        b.push_str(&format!(
            "  neighbor {} activate\n  neighbor {} route-map MNP_EXT_{name}_IN in\n  neighbor {} route-map MNP_EXT_{name}_OUT out\n",
            n.address, n.address, n.address
        ));
    }
    if cfg.maximum_paths > 1 {
        b.push_str(&format!("  maximum-paths {}\n  maximum-paths ibgp {}\n", cfg.maximum_paths, cfg.maximum_paths));
    }
    b.push_str(" exit-address-family\nexit\n!\n");
    files.insert("bgpd", b);

    let needs_bfd = !cfg.bfd.profiles.is_empty() || !cfg.bfd.peers.is_empty();
    if needs_bfd {
        let mut f = header("bfdd");
        f.push_str("bfd\n");
        for p in &cfg.bfd.profiles {
            f.push_str(&format!(
                " profile {}\n  transmit-interval {}\n  receive-interval {}\n  detect-multiplier {}\n",
                p.id, p.transmit_interval, p.receive_interval, p.detect_multiplier
            ));
            if p.passive {
                f.push_str("  passive-mode\n");
            }
            f.push_str(" exit\n !\n");
        }
        for p in &cfg.bfd.peers {
            let mut line = format!(" peer {}", p.address);
            if p.multihop {
                line.push_str(" multihop");
            }
            if let Some(l) = p.local_address {
                line.push_str(&format!(" local-address {l}"));
            }
            if let Some(i) = &p.interface {
                line.push_str(&format!(" interface {i}"));
            }
            f.push_str(&format!("{line}\n  profile {}\n exit\n !\n", p.profile));
        }
        f.push_str("exit\n!\n");
        files.insert("bfdd", f);
    }

    // Every node of the Anycast domain runs ospfd on its carriers, with or without local services. OSPF learns only
    // what these interfaces carry: the carriers' subnet (connected on every member, so never installed from OSPF)
    // and the service stubs, which validation keeps inside the pool.
    if cfg.anycast.enabled {
        let area = &cfg.anycast.area;
        let mut o = header("ospfd");
        for c in &cfg.anycast.interfaces {
            // Point-to-multipoint: no DR, so a dead member only takes its own links (on a broadcast segment the
            // DR's death left every path down for ~5 s in the lab, twice — on failure and when it came back).
            // Prefix suppression keeps the members' carrier /32s out of OSPF: it carries the service stubs only.
            o.push_str(&format!(
                "interface {}\n ip ospf area {area}\n ip ospf network point-to-multipoint\n ip ospf prefix-suppression\n",
                c.name
            ));
            if let Some(cost) = c.cost {
                o.push_str(&format!(" ip ospf cost {cost}\n"));
            }
            if let Some(p) = &c.bfd_profile {
                o.push_str(&format!(" ip ospf bfd\n ip ospf bfd profile {p}\n"));
            }
            o.push_str("exit\n!\n");
        }
        for a in cfg.anycast.instances.iter().filter(|a| a.enabled) {
            // The service prefixes live on their own dummy device: a passive stub, present only while the guard
            // sees the service healthy. Its cost is the metric other nodes compare.
            o.push_str(&format!("interface {}\n ip ospf area {area}\n ip ospf passive\n", a.vip_device()));
            if let Some(m) = a.metric {
                o.push_str(&format!(" ip ospf cost {m}\n"));
            }
            o.push_str("exit\n!\n");
        }
        // No redistribute statements: only the declared VIP stubs and carrier adjacencies exist (§9.5).
        o.push_str(&format!("router ospf\n ospf router-id {rid}\nexit\n!\n"));
        files.insert("ospfd", o);
    }
    Ok(files)
}

pub fn plan(cfg: &FrrConfig, req: &PluginRequest) -> Result<Vec<GenerationPlan>, PluginError> {
    if !cfg.enabled {
        return Ok(Vec::new());
    }
    let files = render(cfg, req)?;
    let dir = "frr/main";
    let mut planned = Vec::new();
    let mut processes = Vec::new();
    let mut checks = vec![CommandSpec {
        provider_slot: None,
        program: Some("/bin/mkdir".into()),
        argv: vec!["-p".into(), format!("/var/run/frr/{PATHSPACE}")],
        timeout_seconds: 5,
        required: true,
    }];
    checks.push(CommandSpec {
        provider_slot: None,
        program: Some("/bin/chown".into()),
        argv: vec!["frr:frr".into(), format!("/var/run/frr/{PATHSPACE}")],
        timeout_seconds: 5,
        required: false,
    });
    // The daemons drop privileges to user `frr` before reading their -f file; planner writes generation files as
    // root. The daemon user owns its (per-apply, immutable) generation directory, like /etc/frr in distributions;
    // modes stay 0640 / 0600 for files with secrets. Without this FRR starts with an empty configuration and only
    // logs "Permission denied" (found in the multi-node lab).
    checks.push(CommandSpec {
        provider_slot: None,
        program: Some("/bin/chown".into()),
        argv: vec!["-R".into(), "frr:frr".into(), format!("${{GENERATION_ROOT}}/{dir}")],
        timeout_seconds: 5,
        required: true,
    });
    // Each daemon is its own binary next to the resolved provider (system FRR or a provider package).
    let provider = req.provider(SLOT)?.path.clone();
    let bin_dir = std::path::Path::new(&provider).parent().map(|p| p.to_string_lossy().into_owned()).unwrap_or_default();
    // zebra first and the other daemons bound to it (what watchfrr does): a daemon that outlives zebra keeps
    // stale interface/connected state, so bgpd's `network` routes stayed invalid and were never advertised again
    // (found in the lab when zebra was restarted under a running bgpd).
    let order = files.keys().filter(|d| **d == "zebra").chain(files.keys().filter(|d| **d != "zebra"));
    for daemon in order {
        let content = &files[daemon];
        let path = format!("{dir}/{daemon}.conf");
        let sensitive = content.contains(" password ");
        planned.push(PlannedFile {
            path: path.clone(),
            mode: if sensitive { "0600".into() } else { "0640".into() },
            content: content.clone(),
            sensitive,
        });
        processes.push(ProcessSpec {
            id: format!("frr/{daemon}"),
            provider_slot: None,
            program: Some(format!("{bin_dir}/{daemon}")),
            argv: vec!["-N".into(), PATHSPACE.into(), "-f".into(), format!("${{GENERATION_ROOT}}/{path}")],
            env: BTreeMap::new(),
            restart: RestartPolicy::OnFailure,
            stop_timeout_seconds: 10,
            reload_signal: None,
            restart_digest: None,
            user: None,
            bound_to: (*daemon != "zebra").then(|| "frr/zebra".to_string()),
        });
    }
    let mut resources = Vec::new();
    // A BGP speaker routes between its LAN, the Tinc mesh and external tunnels: forwarding must be on. (Shared
    // sysctls have no single owner; removing the instance leaves it on, like the other planner features.)
    if cfg.internal_neighbors.iter().any(|n| n.enabled) || cfg.external_neighbors.iter().any(|n| n.enabled) {
        resources.push(NetworkResource::Sysctl { key: "net.ipv4.ip_forward".into(), value: "1".into() });
    }
    let mut guard_procs = Vec::new();
    if cfg.anycast.enabled {
        for a in cfg.anycast.instances.iter().filter(|a| a.enabled) {
            let dev = a.vip_device();
            // Down and without addresses until the guard sees the service healthy. The guard owns the addresses:
            // a down device keeps its local routes, so an unhealthy node would still deliver Anycast traffic of its
            // own clients to the dead local service instead of routing it over OSPF to a healthy one.
            resources.push(NetworkResource::Link { device: dev.clone(), link_type: "dummy".into(), mtu: None, up: false });
            let health = serde_json::to_string(&a.health).map_err(|e| PluginError::new("internal", e.to_string()))?;
            let addresses = a.addresses().into_iter().flat_map(|c| ["--address".to_string(), c]);
            guard_procs.push(ProcessSpec {
                id: format!("frr/anycast-{}", a.id),
                provider_slot: None,
                program: Some(format!("{}/plugins/frr", req.context.libexec_dir.trim_end_matches('/'))),
                argv: [
                    "anycast-guard".into(),
                    "--device".into(),
                    dev,
                    "--state".into(),
                    format!("${{RUN_DIR}}/frr-anycast-{}.state", a.id),
                    "--health".into(),
                    health,
                ]
                .into_iter()
                .chain(addresses)
                .collect(),
                env: BTreeMap::new(),
                restart: RestartPolicy::Always,
                stop_timeout_seconds: 5,
                reload_signal: None,
                restart_digest: None,
                user: None,
                bound_to: None,
            });
        }
    }
    processes.extend(guard_procs);
    Ok(vec![GenerationPlan {
        protocol_version: PLUGIN_PROTOCOL_VERSION,
        request_id: req.request_id.clone(),
        instance: "frr/main".into(),
        files: planned,
        processes,
        resources,
        depends_on: Vec::new(),
        probes: vec![ProbeSpec::Plugin { interval_seconds: 30, params: Value::Null }],
        checks,
        reload: Vec::new(),
    }])
}

