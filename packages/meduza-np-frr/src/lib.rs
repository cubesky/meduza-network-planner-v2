    #[test]
    fn global_prefix_filters_drop_what_they_reject() {
        assert_eq!(parse_filter_rule("permit 0.0.0.0/0 le 32").unwrap().3, Some(32));
        assert_eq!(parse_filter_rule("deny 10.0.0.0/8 ge 16 le 24").unwrap().2, Some(16));
        for bad in ["allow 0.0.0.0/0", "permit 10.0.0.1/8", "permit 10.0.0.0/8 le 4", "permit 10.0.0.0/8 ge 24 le 16", "permit"] {
            assert!(parse_filter_rule(bad).is_none(), "{bad}");
        }
        let mut f = base();
        f["externalNeighbors"][0]["filterIn"] = json!(["deny 0.0.0.0/0", "permit 0.0.0.0/0 le 32"]);
        f["externalNeighbors"][0]["filterOut"] = json!(["deny 0.0.0.0/0", "permit 0.0.0.0/0 le 32"]);
        let r = req(f.clone());
        let cfg = load(&r).unwrap();
        assert!(validate(&cfg, &r).iter().all(|e| !e.path.contains("filter")), "{:?}", validate(&cfg, &r));
        let b = &render(&cfg, &r).unwrap()["bgpd"];
        // inverted: what the filter denies is permitted by the list the leading deny entry matches
        assert!(b.contains("ip prefix-list MNP_EXT_ISP_FIN seq 5 permit 0.0.0.0/0\n"), "{b}");
        assert!(b.contains("ip prefix-list MNP_EXT_ISP_FIN seq 10 deny 0.0.0.0/0 le 32\n"), "{b}");
        assert!(b.contains("ip prefix-list MNP_EXT_ISP_FIN seq 100000 permit 0.0.0.0/0 le 32\n"), "{b}");
        assert!(b.contains("route-map MNP_EXT_ISP_IN deny 2\n match ip address prefix-list MNP_EXT_ISP_FIN\n"), "{b}");
        assert!(b.contains("route-map MNP_EXT_ISP_OUT deny 2\n match ip address prefix-list MNP_EXT_ISP_FOUT\n"), "{b}");
        f["externalNeighbors"][0]["filterIn"] = json!(["accept everything"]);
        let r = req(f);
        assert!(validate(&load(&r).unwrap(), &r).iter().any(|e| e.path == "/externalNeighbors/0/filterIn/0"));
    }

