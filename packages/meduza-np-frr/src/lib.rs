/// One rule of a prefix filter (`permit 0.0.0.0/0 le 32`): (permit, prefix, ge, le).
pub fn parse_filter_rule(rule: &str) -> Option<(bool, Ipv4Net, Option<u8>, Option<u8>)> {
    let mut it = rule.split_whitespace();
    let permit = match it.next()? {
        "permit" => true,
        "deny" => false,
        _ => return None,
    };
    let net: Ipv4Net = it.next()?.parse().ok()?;
    if net.network() != net.addr() {
        return None;
    }
    let (mut ge, mut le) = (None, None);
    while let Some(k) = it.next() {
        let n: u8 = it.next()?.parse().ok().filter(|n| *n >= net.prefix_len() && *n <= 32)?;
        match k {
            "ge" if ge.is_none() => ge = Some(n),
            "le" if le.is_none() => le = Some(n),
            _ => return None,
        }
    }
    if let (Some(g), Some(l)) = (ge, le) {
        if g > l {
            return None;
        }
    }
    Some((permit, net, ge, le))
}

/// The filter as a prefix list with every action inverted plus a final catch-all permit: it matches exactly the
/// routes the filter rejects, so a single `deny` route-map entry applies it ahead of the other entries.
fn rejected_prefix_list(name: &str, rules: &[String], out: &mut String) {
    for (i, r) in rules.iter().filter_map(|r| parse_filter_rule(r)).enumerate() {
        let (permit, net, ge, le) = r;
        let ge = ge.map(|g| format!(" ge {g}")).unwrap_or_default();
        let le = le.map(|l| format!(" le {l}")).unwrap_or_default();
        out.push_str(&format!("ip prefix-list {name} seq {} {} {net}{ge}{le}\n", (i + 1) * 5, if permit { "deny" } else { "permit" }));
    }
    out.push_str(&format!("ip prefix-list {name} seq 100000 permit 0.0.0.0/0 le 32\n"));
}

