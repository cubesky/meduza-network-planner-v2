/// Routes reported per BGP neighbor (the topology view lists them; the counts stay exact).
pub const ROUTES_PER_NEIGHBOR: usize = 64;
/// Distinct AS paths reported per external neighbor (the topology view draws the ASes behind it).
pub const AS_PATHS_PER_NEIGHBOR: usize = 32;

/// `show bgp ipv4 unicast json` → the prefixes each neighbor (by address) sent and that were accepted (valid paths).
pub fn bgp_routes_by_peer(json: &Value) -> BTreeMap<String, Vec<String>> {
    let mut out: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let Some(routes) = json.get("routes").and_then(Value::as_object) else { return out };
    for (prefix, paths) in routes {
        for path in paths.as_array().into_iter().flatten() {
            if path.get("valid").and_then(Value::as_bool) != Some(true) {
                continue;
            }
            let Some(peer) = path.get("peerId").and_then(Value::as_str).filter(|p| p.parse::<IpAddr>().is_ok()) else { continue };
            let list = out.entry(peer.to_string()).or_default();
            if !list.contains(prefix) {
                list.push(prefix.clone());
            }
        }
    }
    out
}

/// IPv4 prefixes this node announces with `network` statements. Anycast VIPs are left out: the guard removes them
/// on purpose while their service is unhealthy (reported by the OSPF/anycast status instead).
pub fn announced_networks(cfg: &FrrConfig, req: &PluginRequest) -> Vec<IpNet> {
    let sets = origin_sets(cfg, req);
    let mut out = Vec::new();
    for p in sets.public.iter().chain(&sets.mappings).chain(&sets.access_pools).chain(&sets.private) {
        if matches!(p, IpNet::V4(_)) && !out.contains(p) {
            out.push(*p);
        }
    }
    out
}

/// `show bgp ipv4 unicast json` → the distinct AS paths of the valid routes each neighbor (by address) sent, as AS
/// numbers with prepending collapsed ("65100 65100 65200" → [65100, 65200]); AS sets and confederation segments
/// (`{..}`, `(..)`) are left out, they say nothing about which AS is behind which.
pub fn bgp_as_paths_by_peer(json: &Value) -> BTreeMap<String, Vec<Vec<u32>>> {
    let mut out: BTreeMap<String, Vec<Vec<u32>>> = BTreeMap::new();
    let Some(routes) = json.get("routes").and_then(Value::as_object) else { return out };
    for paths in routes.values() {
        for path in paths.as_array().into_iter().flatten() {
            if path.get("valid").and_then(Value::as_bool) != Some(true) {
                continue;
            }
            let Some(peer) = path.get("peerId").and_then(Value::as_str).filter(|p| p.parse::<IpAddr>().is_ok()) else { continue };
            let Some(text) = path.get("path").and_then(Value::as_str) else { continue };
            let mut asns: Vec<u32> = Vec::new();
            for asn in text.split_whitespace().map_while(|t| t.parse::<u32>().ok()) {
                if asns.last() != Some(&asn) {
                    asns.push(asn);
                }
            }
            if asns.is_empty() {
                continue;
            }
            let list = out.entry(peer.to_string()).or_default();
            if !list.contains(&asns) && list.len() < AS_PATHS_PER_NEIGHBOR {
                list.push(asns);
            }
        }
    }
    out
}

/// `show bgp neighbors json` → the router ID each neighbor (by address) announced.
pub fn bgp_router_ids(json: &Value) -> BTreeMap<String, String> {
    json.as_object()
        .into_iter()
        .flatten()
        .filter(|(addr, _)| addr.parse::<IpAddr>().is_ok())
        .filter_map(|(addr, n)| Some((addr.clone(), n.get("remoteRouterId")?.as_str()?.to_string())))
        .filter(|(_, id)| id != "0.0.0.0")
        .collect()
}

/// `show bgp ipv4 unicast json` → prefixes with a valid locally originated path (`peerId` "(unspec)").
pub fn local_routes(json: &Value) -> BTreeSet<String> {
    let Some(routes) = json.get("routes").and_then(Value::as_object) else { return BTreeSet::new() };
    routes
        .iter()
        .filter(|(_, paths)| {
            paths.as_array().into_iter().flatten().any(|p| {
                p.get("valid").and_then(Value::as_bool) == Some(true) && p.get("peerId").and_then(Value::as_str) == Some("(unspec)")
            })
        })
        .map(|(prefix, _)| prefix.clone())
        .collect()
}

/// Whether the node's own networks are actually announced. `bgp network import-check` announces a network only
/// while a matching route is in this node's routing table: a LAN whose interface is down, or a LAN that lives
/// outside a bridge-network container's namespace (D41), is silently missing although every session is up.
pub fn origination_status(networks: &[IpNet], local: &BTreeSet<String>, ts: &str) -> Option<InstanceStatus> {
    if networks.is_empty() {
        return None;
    }
    let (originated, missing): (Vec<String>, Vec<String>) = networks.iter().map(IpNet::to_string).partition(|p| local.contains(p));
    let mut detail = BTreeMap::new();
    detail.insert("originated".into(), Value::from(originated));
    detail.insert("notOriginated".into(), Value::from(missing.clone()));
    Some(InstanceStatus {
        id: "frr/main/origination".into(),
        kind: "bgp-origination".into(),
        state: if missing.is_empty() { ServiceState::Up } else { ServiceState::Degraded },
        observed_at: Some(ts.into()),
        reason: (!missing.is_empty()).then(|| {
            format!(
                "not announced: {} (no matching route in this node's routing table; in a bridge-network container the host's LAN is not visible)",
                missing.join(", ")
            )
        }),
        detail,
    })
}

/// What the BGP table and the neighbor details add to the summary, per neighbor address.
#[derive(Debug, Default)]
pub struct PeerDetails {
    /// accepted prefixes ([`bgp_routes_by_peer`])
    pub routes: BTreeMap<String, Vec<String>>,
    /// AS paths of the accepted routes ([`bgp_as_paths_by_peer`]); reported for external neighbors only
    pub as_paths: BTreeMap<String, Vec<Vec<u32>>>,
    /// announced router IDs ([`bgp_router_ids`])
    pub router_ids: BTreeMap<String, String>,
}

/// `show bgp summary json` (+ the routes, AS paths and router IDs per neighbor) → per-neighbor state.
pub fn bgp_statuses(cfg: &FrrConfig, json: &Value, peers_of: &PeerDetails, ts: &str) -> Vec<InstanceStatus> {
    let routes = &peers_of.routes;
    let peers = json.pointer("/ipv4Unicast/peers").and_then(Value::as_object).cloned().unwrap_or_default();
    let mut out = Vec::new();
    let neighbors: Vec<(String, IpAddr, &'static str, Option<&String>)> = cfg
        .internal_neighbors
        .iter()
        .filter(|n| n.enabled)
        .map(|n| (n.id.to_string(), n.address, "internal", n.node.as_ref()))
        .chain(cfg.external_neighbors.iter().filter(|n| n.enabled).map(|n| (n.id.to_string(), n.address, "external", None)))
        .collect();
    for (id, addr, kind, node) in neighbors {
        let p = peers.get(&addr.to_string());
        let st = p.and_then(|p| p.get("state")).and_then(Value::as_str).unwrap_or("Unknown").to_string();
        let mut detail = BTreeMap::new();
        detail.insert("address".into(), Value::String(addr.to_string()));
        detail.insert("session".into(), Value::String(kind.into()));
        detail.insert("bgpState".into(), Value::String(st.clone()));
        if let Some(node) = node {
            detail.insert("node".into(), Value::String(node.clone()));
        }
        if let Some(r) = routes.get(&addr.to_string()) {
            detail.insert("routes".into(), Value::from(r.iter().take(ROUTES_PER_NEIGHBOR).cloned().collect::<Vec<_>>()));
            if r.len() > ROUTES_PER_NEIGHBOR {
                detail.insert("routesTruncated".into(), Value::Bool(true));
            }
        }
        if let Some(paths) = peers_of.as_paths.get(&addr.to_string()).filter(|_| kind == "external") {
            detail.insert("asPaths".into(), Value::from(paths.clone()));
        }
        if let Some(id) = peers_of.router_ids.get(&addr.to_string()) {
            detail.insert("routerId".into(), Value::String(id.clone()));
        }
        if let Some(p) = p {
            for (k, out_k) in [
                ("remoteAs", "remoteAs"),
                ("peerUptime", "uptime"),
                ("pfxRcd", "prefixesReceived"),
                ("pfxSnt", "prefixesSent"),
                ("hostname", "hostname"),
            ] {
                if let Some(v) = p.get(k) {
                    detail.insert(out_k.into(), v.clone());
                }
            }
        }
        out.push(InstanceStatus {
            id: format!("frr/main/bgp-{id}"),
            kind: "bgp-neighbor".into(),
            state: match st.as_str() {
                "Established" => ServiceState::Up,
                "Unknown" => ServiceState::Unknown,
                "Idle (Admin)" => ServiceState::Disabled,
                _ => ServiceState::Down,
            },
            observed_at: Some(ts.into()),
            reason: None,
            detail,
        });
    }
    out
}

/// `show bfd peers json`.
pub fn bfd_statuses(json: &Value, ts: &str) -> Vec<InstanceStatus> {
    json.as_array()
        .into_iter()
        .flatten()
        .map(|p| {
            let peer = p.get("peer").and_then(Value::as_str).unwrap_or("?");
            let status = p.get("status").and_then(Value::as_str).unwrap_or("unknown");
            let mut detail = BTreeMap::new();
            for k in [
                "peer",
                "local",
                "status",
                "diagnostic",
                "remote-diagnostic",
                "multihop",
                "transmit-interval",
                "receive-interval",
                "detect-multiplier",
                "uptime",
                "downtime",
            ] {
                if let Some(v) = p.get(k) {
                    detail.insert(k.replace('-', "_"), v.clone());
                }
            }
            InstanceStatus {
                id: format!("frr/main/bfd-{}", peer.replace(['.', ':'], "-")),
                kind: "bfd-peer".into(),
                state: match status {
                    "up" => ServiceState::Up,
                    "down" => ServiceState::Down,
                    "init" => ServiceState::Starting,
                    _ => ServiceState::Unknown,
                },
                observed_at: Some(ts.into()),
                reason: p.get("diagnostic").and_then(Value::as_str).filter(|d| *d != "ok").map(str::to_string),
                detail,
            }
        })
        .collect()
}

/// `show ip ospf neighbor json` (+ anycast guard state files).
pub fn ospf_statuses(cfg: &FrrConfig, json: &Value, guard_states: &BTreeMap<String, String>, ts: &str) -> Vec<InstanceStatus> {
    let mut out = Vec::new();
    if let Some(neigh) = json.get("neighbors").and_then(Value::as_object) {
        for (rid, entries) in neigh {
            for e in entries.as_array().into_iter().flatten() {
                let state = e.get("nbrState").or_else(|| e.get("state")).and_then(Value::as_str).unwrap_or("?");
                let mut detail = BTreeMap::new();
                detail.insert("routerId".into(), Value::String(rid.clone()));
                detail.insert("ospfState".into(), Value::String(state.into()));
                if let Some(i) = e.get("ifaceName").or_else(|| e.get("interfaceName")) {
                    detail.insert("interface".into(), i.clone());
                }
                out.push(InstanceStatus {
                    id: format!("frr/main/ospf-{}", rid.replace('.', "-")),
                    kind: "ospf-neighbor".into(),
                    state: if state.starts_with("Full") { ServiceState::Up } else { ServiceState::Starting },
                    observed_at: Some(ts.into()),
                    reason: None,
                    detail,
                });
            }
        }
    }
    for a in cfg.anycast.instances.iter().filter(|a| a.enabled && cfg.anycast.enabled) {
        let raw = guard_states.get(a.id.as_str()).map(String::as_str).unwrap_or("");
        let healthy = raw.starts_with("healthy");
        let mut detail = BTreeMap::new();
        detail.insert("service".into(), Value::String(a.service.clone()));
        detail.insert("vips".into(), Value::String(a.prefixes.iter().map(|p| p.to_string()).collect::<Vec<_>>().join(",")));
        detail.insert("announced".into(), Value::Bool(healthy));
        detail.insert("guard".into(), Value::String(if raw.is_empty() { "no state yet".into() } else { raw.trim().to_string() }));
        out.push(InstanceStatus {
            id: format!("frr/main/anycast-{}", a.id),
            kind: "anycast".into(),
            state: if raw.is_empty() {
                ServiceState::Unknown
            } else if healthy {
                ServiceState::Up
            } else {
                ServiceState::Down
            },
            observed_at: Some(ts.into()),
            reason: (!healthy && !raw.is_empty()).then(|| "service unhealthy: VIP withdrawn".to_string()),
            detail,
        });
    }
    out
}

