// Import of the previous service planner's etcd export (`meduza-etcd-export-v1`, D58). The export is a flat key/value
// dump; this module turns it into a cluster document plus the list of values the operator still has to supply
// (secrets the export carries redacted, peer public keys), and notes on what is not taken over.
//
// Taken over: /dns/hosts, /global/bgp (filter, max_paths), /global/clash/subscriptions, /global/mosdns, /global/tinc,
// /nodes/<id>/* except ospf and easytier. Not taken over: /updated/* and /update/* (status uploaded by the old
// nodes), /commit, /global/ospf, /global/easytier, /global/internal_routing_system and /global/mesh_type (fixed here:
// BGP over one Tinc mesh), /global/bgp/edge_broadcast.

import type { ClusterDocument, NodeSpec } from "../cluster.js";
import type { SecretKind } from "../secrets.js";

export const EXPORT_FORMAT = "meduza-etcd-export-v1";
const REDACTED = "[REDACTED]";

export interface EtcdExport {
  format: string;
  kvs: Array<{ key: string; value: string; value_encoding?: string }>;
}

/** A value the import needs: a secret (stored encrypted) or a public key written into the document. */
export interface ImportNeed {
  /** secret id, or `public:<document path>` for a public key */
  id: string;
  kind: SecretKind | "public-key";
  label: string;
  node?: string;
  /** what uses it (document path) */
  usedBy: string;
  /** present in the export (not redacted) */
  value?: string;
  /** generated by the import when not supplied (API secrets) */
  generated?: boolean;
  /** what stays off until the value is supplied (document path of an `enabled` flag) */
  disables?: string;
}

export interface ImportedNode {
  /** id in the export */
  source: string;
  id: string;
  displayName: string;
  behavior: "static" | "roaming";
}

export interface ImportResult {
  document: ClusterDocument;
  nodes: ImportedNode[];
  needs: ImportNeed[];
  /** node-held keys to generate on the nodes (Tinc keys the export carries redacted) */
  nodeKeys: Array<{ node: string; secretId: string; keyKind: SecretKind; package: string }>;
  notes: string[];
}

/** Lowercase stable id (`Site-A1` → `site-a1`). */
export function stableId(name: string): string {
  const s = name
    .toLowerCase()
    .replace(/[^a-z0-9_-]+/g, "-")
    .replace(/^[^a-z0-9]+/, "")
    .slice(0, 63);
  return s || "x";
}

const lines = (v: string | undefined) =>
  (v ?? "")
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));
const bool = (v: string | undefined) => v === "true" || v === "1" || v === "yes";
const num = (v: string | undefined) => (v !== undefined && /^\d+$/.test(v.trim()) ? Number(v.trim()) : undefined);
const redacted = (v: string | undefined) => v === REDACTED;
/** The most frequent value (ties: the first seen). */
function mode<T>(values: T[]): T | undefined {
  const count = new Map<T, number>();
  for (const v of values) count.set(v, (count.get(v) ?? 0) + 1);
  return [...count].sort((a, b) => b[1] - a[1])[0]?.[0];
}

/** Children of `prefix` as a nested object of strings (`a/b` → { a: { b } }). */
function tree(kv: Map<string, string>, prefix: string): Record<string, any> {
  const out: Record<string, any> = {};
  for (const [k, v] of kv) {
    if (!k.startsWith(prefix)) continue;
    const parts = k.slice(prefix.length).split("/").filter(Boolean);
    let at = out;
    parts.forEach((p, i) => {
      if (i === parts.length - 1) at[p] = v;
      else at = at[p] = typeof at[p] === "object" ? at[p] : {};
    });
  }
  return out;
}

export function convertEtcdExport(input: unknown): ImportResult {
  const exp = input as EtcdExport;
  if (!exp || exp.format !== EXPORT_FORMAT || !Array.isArray(exp.kvs)) throw new Error(`not a ${EXPORT_FORMAT} export`);
  const kv = new Map<string, string>();
  for (const e of exp.kvs) {
    if (typeof e?.key !== "string") continue;
    if (e.value_encoding && e.value_encoding !== "utf-8") continue; // binary values are not configuration
    kv.set(e.key, String(e.value ?? ""));
  }
  const notes: string[] = [];
  const needs: ImportNeed[] = [];
  const nodeKeys: ImportResult["nodeKeys"] = [];
  const need = (n: ImportNeed) => {
    if (!needs.some((x) => x.id === n.id)) needs.push(n);
  };
  const ignored = new Set<string>();
  for (const k of kv.keys()) {
    const top = k.split("/").slice(0, 3).join("/");
    if (/^\/(updated?|commit)(\/|$)/.test(k)) ignored.add(k.startsWith("/commit") ? "/commit" : `/${k.split("/")[1]}/… (status uploaded by the old nodes)`);
    else if (/^\/global\/(ospf|easytier|internal_routing_system|mesh_type)/.test(k)) ignored.add(top);
    else if (k === "/global/bgp/edge_broadcast") ignored.add(k);
    else if (/^\/nodes\/[^/]+\/(ospf|easytier)\//.test(k)) ignored.add(`/nodes/*/${k.split("/")[3]}`);
  }
  const g = tree(kv, "/global/");
  const doc: ClusterDocument & Record<string, any> = { schemaVersion: 1, nodes: {} };

  // ---- DNS hosts ----------------------------------------------------------------------------------------------
  const hosts = Object.entries(tree(kv, "/dns/hosts/"))
    .filter(([, v]) => typeof v === "string")
    .map(([hostname, v]) => ({ hostname, ips: lines(v as string).map((ip) => ip.replace(/^\[(.*)\]$/, "$1")) }))
    .filter((h) => h.ips.length);
  if (hosts.length) doc.dns = { hosts };

  // ---- Tinc mesh defaults ------------------------------------------------------------------------------------
  // OpenSSL names are case-insensitive for tinc; the plugin accepts the lowercase spelling (`SHA512` → `sha512`)
  if (g.tinc?.cipher || g.tinc?.digest) doc.tinc = { ...(g.tinc.cipher ? { cipher: g.tinc.cipher.toLowerCase() } : {}), ...(g.tinc.digest ? { digest: g.tinc.digest.toLowerCase() } : {}) };
  if (g.tinc?.netname) notes.push(`Tinc netname "${g.tinc.netname}" is not needed: the cluster has one mesh (D22).`);

  // ---- BGP ----------------------------------------------------------------------------------------------------
  const rawNodes = tree(kv, "/nodes/");
  const nodeIds = Object.keys(rawNodes).sort();
  const asns = nodeIds.map((n) => num(rawNodes[n]?.bgp?.local_asn)).filter((x): x is number => x !== undefined);
  const internalAsn = mode(asns);
  const routing: NonNullable<ClusterDocument["routing"]> = {};
  if (internalAsn !== undefined) routing.internalAsn = internalAsn;
  const maxPaths = num(g.bgp?.max_paths) ?? mode(nodeIds.map((n) => num(rawNodes[n]?.bgp?.max_paths)).filter((x): x is number => x !== undefined));
  if (maxPaths !== undefined) routing.maximumPaths = Math.min(64, Math.max(1, maxPaths));
  const filterIn = lines(g.bgp?.filter?.in);
  const filterOut = lines(g.bgp?.filter?.out);
  if (filterIn.length || filterOut.length) routing.bgpFilter = { ...(filterIn.length ? { in: filterIn } : {}), ...(filterOut.length ? { out: filterOut } : {}) };
  if (Object.keys(routing).length) doc.routing = routing;
  if (nodeIds.some((n) => rawNodes[n]?.bgp?.max_paths && num(rawNodes[n].bgp.max_paths) !== maxPaths)) {
    notes.push("Per-node BGP max_paths differs from the cluster value; the cluster value is used everywhere.");
  }

  // ---- Clash → Mihomo subscriptions ---------------------------------------------------------------------------
  const subs = Object.entries((g.clash?.subscriptions ?? {}) as Record<string, { url?: string }>).filter(([, s]) => s && typeof s === "object" && s.url !== undefined);
  if (subs.length) {
    const active = mode(nodeIds.map((n) => rawNodes[n]?.clash?.active_subscription).filter(Boolean));
    const minutes = mode(nodeIds.map((n) => num(rawNodes[n]?.clash?.refresh?.interval_minutes)).filter((x): x is number => x !== undefined));
    doc.mihomo = {
      subscriptions: subs.map(([name, s]) => {
        const urlRef = `mihomo-sub-${stableId(name)}`;
        need({ id: urlRef, kind: "text", label: `Clash subscription URL "${name}"`, usedBy: "/mihomo/subscriptions", ...(redacted(s.url) ? {} : { value: s.url }) });
        return { id: stableId(name), name, urlRef };
      }),
      default: stableId(active && subs.some(([n]) => n === active) ? active : subs[0]![0]),
      ...(minutes ? { refreshSeconds: Math.max(60, minutes * 60) } : {}),
    };
  }

  // ---- MosDNS ---------------------------------------------------------------------------------------------------
  if (g.mosdns) {
    const m = g.mosdns as Record<string, string>;
    const listen = /listen:\s*["']?([\d.]+):(\d+)/.exec(m.plugins ?? "");
    let ruleFiles: Array<Record<string, unknown>> = [];
    try {
      const files = JSON.parse(m.rule_files || "{}") as Record<string, string>;
      const refreshHours = Math.max(1, Math.round((num(m.refresh) ?? 1440) / 60));
      ruleFiles = Object.entries(files).map(([fileName, url]) => ({ id: stableId(fileName.replace(/\.txt$/, "")), fileName, url, refreshHours }));
    } catch {
      notes.push("/global/mosdns/rule_files is not valid JSON; no rule files imported.");
    }
    doc.mosdns = {
      listen: listen?.[1] ?? "0.0.0.0",
      port: listen ? Number(listen[2]) : 1153,
      ...(m.plugins ? { pluginsYaml: m.plugins.replace(/\s+$/, "") + "\n" } : {}),
      domains: { local: lines(m.local), block: lines(m.block), ddns: lines(m.ddns), global: lines(m.global) },
      ruleFiles,
    };
  }

  // ---- nodes --------------------------------------------------------------------------------------------------
  const nodes: ImportedNode[] = [];
  for (const source of nodeIds) {
    const n = rawNodes[source] as Record<string, any>;
    const id = stableId(source);
    const behavior = n.behavior === "roaming" ? "roaming" : "static";
    nodes.push({ source, id, displayName: source, behavior });
    const base = `/nodes/${id}`;
    const spec: NodeSpec & Record<string, any> = { displayName: source, behavior, services: {} };
    if (n.router_id) spec.routerId = n.router_id;
    const lan = lines(n.lan);
    if (lan.length) {
      spec.networks = { lan };
      spec.routing = { originate: { lan: true } };
    }
    const ownAsn = num(n.bgp?.local_asn);
    const services = spec.services!;

    // Tinc
    if (n.tinc) {
      const t = n.tinc;
      const secretId = `tinc-${id}`;
      services.tinc = {
        enabled: bool(t.enable),
        privateKeyRef: secretId,
        ...(t.ipv4 ? { address: t.ipv4 } : {}),
        ...(t.address ? { publicAddresses: [t.address] } : {}),
        ...(num(t.port) ? { port: num(t.port) } : {}),
        ...(t.dev_name ? { device: t.dev_name } : {}),
      };
      if (t.private_key && !redacted(t.private_key)) {
        need({ id: secretId, kind: "tinc-rsa-private", label: `Tinc private key of ${source}`, node: id, usedBy: `${base}/services/tinc`, value: t.private_key });
      } else {
        nodeKeys.push({ node: id, secretId, keyKind: "tinc-rsa-private", package: "meduza-np-tinc" });
      }
    }
    if (ownAsn !== undefined && ownAsn !== internalAsn) spec.routing = { ...spec.routing, asn: ownAsn };
    if (n.bgp?.enable === "false") notes.push(`${source}: BGP was disabled; Tinc mesh members always run iBGP here (D25).`);

    // Clash → Mihomo
    if (n.clash) {
      const c = n.clash;
      const apiRef = `mihomo-api-${id}`;
      need({ id: apiRef, kind: "text", label: `Mihomo API secret of ${source}`, node: id, usedBy: `${base}/services/mihomo/api`, generated: true });
      const ports = lines(c.exclude_tproxy_port).map(Number).filter((p) => Number.isInteger(p) && p > 0 && p < 65536);
      const minutes = num(c.refresh?.interval_minutes);
      const clusterMinutes = (doc.mihomo?.refreshSeconds ?? 0) / 60;
      services.mihomo = {
        enabled: bool(c.enable),
        mode: c.mode === "tproxy" ? "tproxy" : "proxy",
        api: { secretRef: apiRef },
        ...(c.active_subscription && stableId(c.active_subscription) !== doc.mihomo?.default ? { subscription: stableId(c.active_subscription) } : {}),
        ...(minutes && minutes !== clusterMinutes ? { refreshSeconds: Math.max(60, minutes * 60) } : {}),
        ...(c.mode === "tproxy"
          ? {
              tproxy: {
                ...(c.tproxy_protocol ? { protocols: c.tproxy_protocol === "tcp" ? "tcp" : c.tproxy_protocol === "udp" ? "udp" : "both" } : {}),
                ...(ports.length ? { excludePorts: ports } : {}),
                ...(c.exclude_rfc1918 !== undefined ? { excludePrivateDestinations: bool(c.exclude_rfc1918) } : {}),
                ...(c.use_conntrack !== undefined ? { useConntrack: bool(c.use_conntrack) } : {}),
              },
            }
          : {}),
      };
      if (c.refresh?.enable === "false") notes.push(`${source}: subscription refresh was off; it refreshes automatically here.`);
    }

    // dnsmasq: the export has no listen addresses or fallback servers
    if (n.dnsmasq) {
      services.dnsmasq = { enabled: false, listenAddresses: [], fallbackServers: [] };
      if (bool(n.dnsmasq.enable)) notes.push(`${source}: dnsmasq was enabled; it is imported switched off: set its listen addresses and fallback servers, then enable it.`);
    }

    // MosDNS: the shared configuration (cluster `mosdns`) on this node
    if (n.mosdns) services.mosdns = { enabled: bool(n.mosdns.enable) };

    // OpenVPN
    const ovpn = Object.entries((n.openvpn ?? {}) as Record<string, any>).filter(([, v]) => v && typeof v === "object");
    if (ovpn.length) {
      services.openvpn = {
        ...(n.openvpn.enable !== undefined ? { enabled: bool(n.openvpn.enable) } : {}),
        instances: ovpn.map(([name, o], i) => {
          const iid = stableId(name);
          const path = `${base}/services/openvpn/instances/${i}`;
          const server = String(o.proto ?? "").endsWith("server");
          const [local, remote] = String(o.ifconfig ?? "").split(/\s+/);
          const [interval, timeout] = String(o.keepalive ?? "").split(/\s+/).map(Number);
          const ref = (field: string, kind: SecretKind, label: string) => {
            if (o[field] === undefined) return undefined;
            const sid = `ovpn-${id}-${iid}-${field.replace(/_/g, "-")}`;
            need({ id: sid, kind, label: `${label} of OpenVPN ${name} on ${source}`, node: id, usedBy: path, disables: `${path}/enabled`, ...(redacted(o[field]) ? {} : { value: o[field] }) });
            return sid;
          };
          const tls = {
            ...(ref("ca", "pem-certificate", "CA certificate") ? { caRef: `ovpn-${id}-${iid}-ca` } : {}),
            ...(ref("cert", "pem-certificate", "certificate") ? { certRef: `ovpn-${id}-${iid}-cert` } : {}),
            ...(ref("key", "pem-private-key", "private key") ? { keyRef: `ovpn-${id}-${iid}-key` } : {}),
            ...(ref("tls_auth", "openvpn-static-key", "tls-auth key") ? { tlsAuthRef: `ovpn-${id}-${iid}-tls-auth` } : {}),
            ...(ref("tls_crypt", "openvpn-tls-crypt", "tls-crypt key") ? { tlsCryptRef: `ovpn-${id}-${iid}-tls-crypt` } : {}),
            ...(num(o.key_direction) !== undefined ? { keyDirection: num(o.key_direction) } : {}),
            ...(o.remote_cert_tls ? { remoteCertTls: o.remote_cert_tls } : {}),
          };
          const staticKeyRef = ref("secret", "openvpn-static-key", "static key");
          const bgp = o.bgp && num(o.bgp.peer_asn) !== undefined
            ? {
                ...(o.bgp.enable === "false" ? { enabled: false } : {}),
                remoteAsn: num(o.bgp.peer_asn),
                ...(o.bgp.peer_ip ? { address: o.bgp.peer_ip } : {}),
                // the old filters let everything through: no implicit transit protection, everything advertised
                noTransit: bool(o.bgp.no_transit),
                noForward: false,
                exportInternal: true,
              }
            : undefined;
          return {
            id: iid,
            name,
            enabled: bool(o.enable),
            kind: "site2site",
            role: server ? "server" : "client",
            topology: "p2p",
            proto: String(o.proto ?? "udp").startsWith("tcp") ? "tcp" : "udp",
            ...(o.dev ? { device: o.dev } : {}),
            ...(num(o.port) ? { port: num(o.port) } : {}),
            ...(!server && o.remote ? { remotes: [{ host: o.remote, ...(num(o.port) ? { port: num(o.port) } : {}) }] } : {}),
            ...(local ? { ifconfig: { local, ...(remote ? { remote } : {}) } } : {}),
            ...(interval && timeout ? { keepalive: { interval, timeout } } : {}),
            ...(o.cipher ? { cipher: o.cipher } : {}),
            ...(o.auth ? { auth: o.auth } : {}),
            ...(o.comp_lzo === "yes" ? { compression: "lzo-asym" } : o.comp_lzo === "no" ? { compression: "lzo-no" } : {}),
            ...(o.persist_tun !== undefined ? { persistTun: bool(o.persist_tun) } : {}),
            ...(num(o.verb) !== undefined ? { verb: num(o.verb) } : {}),
            ...(!server && (bool(o.client) || bool(o.pull)) ? { p2pPull: true } : {}),
            ...(staticKeyRef ? { staticKeyRef } : {}),
            ...(Object.keys(tls).length ? { tls } : {}),
            ...(bgp ? { bgp } : {}),
          };
        }),
      };
    } else if (n.openvpn?.enable !== undefined) {
      services.openvpn = { enabled: bool(n.openvpn.enable), instances: [] };
    }

    // WireGuard
    const wg = Object.entries((n.wireguard ?? {}) as Record<string, any>).filter(([, v]) => v && typeof v === "object");
    if (wg.length) {
      services.wireguard = {
        instances: wg.map(([name, w], i) => {
          const iid = stableId(name);
          const path = `${base}/services/wireguard/instances/${i}`;
          const keyRef = `wg-${id}-${iid}`;
          need({ id: keyRef, kind: "wireguard-private-key", label: `WireGuard private key of ${name} on ${source}`, node: id, usedBy: path, disables: `${path}/enabled`, ...(redacted(w.private_key) || !w.private_key ? {} : { value: w.private_key }) });
          const peers = Object.entries((w.peer ?? {}) as Record<string, any>).map(([pname, p], j) => {
            const ppath = `${path}/peers/${j}`;
            need({ id: `public:${ppath}/publicKey`, kind: "public-key", label: `public key of peer ${pname} (${name} on ${source})`, node: id, usedBy: ppath, disables: `${path}/enabled`, ...(redacted(p.public_key) || !p.public_key ? {} : { value: p.public_key }) });
            return {
              id: stableId(pname),
              name: pname,
              ...(p.endpoint ? { endpoint: p.endpoint } : {}),
              ...(num(p.persistent_keepalive) ? { persistentKeepalive: num(p.persistent_keepalive) } : {}),
              // the export has no AllowedIPs: one peer per interface, routes come from BGP
              allowedIps: ["0.0.0.0/0"],
              ...(j === 0 && w.bgp && num(w.bgp.peer_asn) !== undefined
                ? { bgp: { remoteAsn: num(w.bgp.peer_asn), ...(w.bgp.peer_ip ? { address: w.bgp.peer_ip } : {}), noTransit: bool(w.bgp.no_transit), noForward: false, exportInternal: true } }
                : {}),
            };
          });
          return {
            id: iid,
            name,
            enabled: bool(w.enable),
            ...(w.dev ? { device: w.dev } : {}),
            ...(w.address ? { addresses: [w.address] } : {}),
            ...(num(w.listen_port) ? { listenPort: num(w.listen_port) } : {}),
            privateKeyRef: keyRef,
            peers,
          };
        }),
      };
    }
    doc.nodes[id] = spec;
  }
  if (ignored.size) notes.unshift(`Not imported: ${[...ignored].sort().join(", ")}.`);
  return { document: doc, nodes, needs, nodeKeys, notes };
}

/** Sets `value` at a JSON-pointer-like `/a/b/0/c` path of `doc`. */
export function setPath(doc: Record<string, any>, path: string, value: unknown): void {
  const parts = path.split("/").filter(Boolean);
  let at: any = doc;
  for (const p of parts.slice(0, -1)) {
    if (at[p] === undefined) return;
    at = at[p];
  }
  at[parts[parts.length - 1]!] = value;
}
