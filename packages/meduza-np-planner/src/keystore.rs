//! Node-held secrets (§6.3 default: private keys stay on the node that generated them).
//!
//! Stored as `/etc/meduza-np/keys/<secretId>.json` (0600) with `{kind, value, publicValue}`; merged into plugin
//! requests next to the manager-delivered secrets. Only the public value ever leaves the node.

use std::io;
use std::path::{Path, PathBuf};

use base64::Engine;
use meduza_np_protocol::config::SecretValue;
use meduza_np_protocol::ids::validate_stable_id;
use meduza_np_runtime::fsutil;
use serde::{Deserialize, Serialize};

#[derive(Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct StoredKey {
    pub kind: String,
    pub value: String,
    pub public_value: Option<String>,
}

pub struct KeyStore {
    dir: PathBuf,
}

fn valid_id(id: &str) -> bool {
    // Secret ids may contain '.', which stable ids do not; keep the same safe charset otherwise.
    !id.is_empty() && id.len() <= 96 && validate_stable_id(&id.replace('.', "-")).is_ok()
}

impl KeyStore {
    pub fn new(dir: &Path) -> Self {
        Self { dir: dir.to_owned() }
    }

    fn path(&self, id: &str) -> io::Result<PathBuf> {
        if !valid_id(id) {
            return Err(io::Error::new(io::ErrorKind::InvalidInput, "invalid secret id"));
        }
        Ok(self.dir.join(format!("{id}.json")))
    }

    pub fn get(&self, id: &str) -> io::Result<Option<StoredKey>> {
        fsutil::read_json(&self.path(id)?, 64 * 1024)
    }

    pub fn as_secret(&self, id: &str) -> Option<SecretValue> {
        self.get(id).ok().flatten().map(|k| SecretValue { kind: k.kind, value: k.value })
    }

    pub fn put(&self, id: &str, key: &StoredKey) -> io::Result<()> {
        fsutil::ensure_dir(&self.dir, 0o700)?;
        fsutil::write_json_atomic(&self.path(id)?, key, 0o600)
    }

    /// Generates a key of `kind` locally and returns its public value. Existing keys are only replaced with
    /// `replace = true` (regeneration invalidates existing peers, §6.3).
    pub fn generate(&self, id: &str, kind: &str, replace: bool) -> io::Result<String> {
        if !replace {
            if let Some(existing) = self.get(id)? {
                if existing.kind == kind {
                    return existing.public_value.ok_or_else(|| io::Error::other("stored key has no public value"));
                }
            }
        }
        let key = match kind {
            "wireguard-private-key" => {
                let mut seed = [0u8; 32];
                getrandom::getrandom(&mut seed).map_err(|e| io::Error::other(e.to_string()))?;
                let secret = x25519_dalek::StaticSecret::from(seed);
                let public = x25519_dalek::PublicKey::from(&secret);
                let b64 = base64::engine::general_purpose::STANDARD;
                StoredKey { kind: kind.into(), value: b64.encode(secret.to_bytes()), public_value: Some(b64.encode(public.as_bytes())) }
            }
            "wireguard-psk" => {
                let mut psk = [0u8; 32];
                getrandom::getrandom(&mut psk).map_err(|e| io::Error::other(e.to_string()))?;
                // A PSK is shared by both peers, so it is not node-held; generate on the manager instead.
                let _ = psk;
                return Err(io::Error::new(io::ErrorKind::Unsupported, "pre-shared keys are generated on the manager"));
            }
            other => return Err(io::Error::new(io::ErrorKind::Unsupported, format!("key kind {other} must be generated by its plugin"))),
        };
        self.put(id, &key)?;
        Ok(key.public_value.clone().unwrap_or_default())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wireguard_keys_are_real_x25519() {
        let dir = std::env::temp_dir().join(format!("mnp-keys-{}", std::process::id()));
        let ks = KeyStore::new(&dir);
        let public = ks.generate("wg-uplink", "wireguard-private-key", false).unwrap();
        let again = ks.generate("wg-uplink", "wireguard-private-key", false).unwrap();
        assert_eq!(public, again, "existing key is kept unless replace is requested");
        let stored = ks.get("wg-uplink").unwrap().unwrap();
        let b64 = base64::engine::general_purpose::STANDARD;
        let secret: [u8; 32] = b64.decode(&stored.value).unwrap().try_into().unwrap();
        let derived = x25519_dalek::PublicKey::from(&x25519_dalek::StaticSecret::from(secret));
        assert_eq!(b64.encode(derived.as_bytes()), public);
        assert_ne!(ks.generate("wg-uplink", "wireguard-private-key", true).unwrap(), public);
        assert!(ks.path("../etc/passwd").is_err());
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
